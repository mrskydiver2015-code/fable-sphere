export function makeMatrixDemo(now = Date.now()): LibraryEntry[] {
  return categories.flatMap((category, group) =>
    category.items.map((item, index) => {
      const divider = item.lastIndexOf(":");
      const name = item.slice(0, divider),
        type = item.slice(divider + 1);
      const id = `matrix-${category.id}-${index}`;
      const image = type === "Image" || type === "Moodboard";
      return {
        key: keyFor(id, "demo"),
        id,
        space: "demo",
        kind: "asset",
        parentId: null,
        name,
        type: image ? "Image" : type,
        category: category.name,
        headerColor: category.color,
        seed: group * 10 + index,
        art: image ? "landscape" : group % 2 ? "abstract" : "paper",
        desc: `Demo ${type.toLowerCase()} from ${category.name}.`,
        created: now - (group * 10 + index + 30) * 86400000,
        updated: now - (group * 10 + index + 30) * 86400000,
        ...(image
          ? { demoArt: true, mime: "image/svg+xml" }
          : {
              mime: "text/plain",
              text: `${name}\n\n${category.name} · ${type}\n\nSample content for exploring the Fable Sphere cylinder.\nThis is a mock entry; no original file or live bookmark is attached.`,
            }),
      };
    }),
  );
}
