export function makeShowcase(now = Date.now()): LibraryEntry[] {
  return covers.map((cover, index) => {
    const id = `showcase-${index}`;
    return {
      key: keyFor(id, "showcase"),
      id,
      space: "showcase",
      kind: "asset",
      parentId: null,
      name: cover.name,
      category: cover.category,
      headerColor: cover.color,
      desc: `An original illustrated project cover from ${cover.category}. Open the full-resolution artwork to explore the scene.`,
      type: "Image",
      mime: "image/svg+xml",
      demoArt: true,
      thumbnail: `/showcase/${cover.file}`,
      seed: index,
      art: "landscape",
      created: now - index * 86400000,
      updated: now - index * 86400000,
    };
  });
}
